-- Tables mapped by JPA entities that were absent from cca_db.
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS dashboard_management.asp_audit_report (
    asp_audit_report_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aspid bigint,
    file_name character varying(200),
    audit_report_date timestamp(6) without time zone
);

CREATE TABLE IF NOT EXISTS license_issuance_management.license_review (
    license_review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_app_id character varying(255) NOT NULL,
    username character varying(50) NOT NULL,
    serial_no character varying(24) NOT NULL,
    issue_date timestamp(6) without time zone NOT NULL,
    expiry_date timestamp(6) without time zone NOT NULL,
    public_key text NOT NULL,
    application_kind character varying(10) NOT NULL,
    status character varying(40) NOT NULL,
    cca_remark text,
    ca_serial integer NOT NULL,
    key_sequence integer NOT NULL,
    submitted_by character varying(74) NOT NULL,
    reviewed_by character varying(74),
    created timestamp(6) without time zone NOT NULL,
    updated timestamp(6) without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS license_issuance_management.renewal_window_extension (
    extension_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id bigint,
    username character varying(74) NOT NULL,
    licensename character varying(200),
    serial_no character varying(50),
    granted_on date NOT NULL,
    extension_until date NOT NULL,
    granted_by character varying(74) NOT NULL,
    remarks text,
    status character varying(10) NOT NULL,
    created timestamp(6) without time zone NOT NULL,
    updated timestamp(6) without time zone NOT NULL
);
